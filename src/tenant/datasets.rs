use super::{
    TenantHandle,
    catalog::*,
    retention::{self, Expiration},
};
use crate::{Error, Result, model::*, storage::Transaction};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use uuid::Uuid;

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Publication {
    pub version: Uuid,
    pub collection: String,
    /// Optional default Lookup. Empty publishes a dataset without a Lookup.
    #[serde(default)]
    pub lookup: String,
    pub expected_version: Option<Uuid>,
    #[serde(default)]
    pub retry_token: Option<Uuid>,
}
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct PublishedLookup {
    #[serde(default)]
    pub version: Uuid,
    pub name: String,
    pub publication: Publication,
    pub collection_id: Uuid,
    pub commit_seq: u64,
}
#[derive(Serialize, Deserialize)]
pub struct PublishedResult {
    pub version: Uuid,
    pub result: LookupResult,
}

#[derive(Serialize, Deserialize)]
struct PublicationReceipt {
    request: Publication,
    result: PublishedLookup,
    principal: String,
}
pub(crate) fn parse_published(bytes: &[u8]) -> Result<PublishedLookup> {
    let mut out: PublishedLookup = parse(bytes)?;
    if out.version.is_nil() {
        out.version = out.publication.version;
    }
    Ok(out)
}

pub(crate) fn mutable(tx: &Transaction<'_>, collection: Uuid) -> Result<()> {
    if tx.get(&prefix(b'S', collection))?.is_some() {
        return Err(Error::new(
            "IMMUTABLE_DATASET",
            "published collections are immutable; prepare a new collection",
        ));
    }
    Ok(())
}

impl TenantHandle {
    /// Atomically publish and freeze a collection. `publication.version` is the
    /// request ID; the returned `version` is generated by the engine and never reused.
    pub fn publish_lookup(
        &self,
        resource: &str,
        publication: Publication,
    ) -> Result<PublishedLookup> {
        self.publish_lookup_with(resource, publication, "embedded")
    }
    pub fn publish_lookup_with(
        &self,
        resource: &str,
        publication: Publication,
        principal: &str,
    ) -> Result<PublishedLookup> {
        if publication.lookup.is_empty() {
            return Err(Error::invalid("lookup publication requires a lookup"));
        }
        self.publish_dataset_with(resource, publication, principal)
    }

    /// Freeze and publish a collection even when it has no Lookup definition.
    /// The returned version, not the request ID, identifies immutable data.
    pub fn publish_dataset(
        &self,
        resource: &str,
        publication: Publication,
    ) -> Result<PublishedLookup> {
        self.publish_dataset_with(resource, publication, "embedded")
    }

    pub fn publish_dataset_with(
        &self,
        resource: &str,
        publication: Publication,
        principal: &str,
    ) -> Result<PublishedLookup> {
        name(resource)?;
        name(principal)?;
        if publication.version.is_nil() {
            return Err(Error::invalid("non-nil publication request ID required"));
        }
        crate::identity::unmanaged(&publication.collection)?;
        let _permit = self.core.gate.enter()?;
        self.touch();
        self.engine().transact(|tx| {
            let receipt_key =
                retention::key(retention::PUBLICATIONS, publication.version.as_bytes());
            if let Some(bytes) = tx.get(&receipt_key)? {
                retention::check_tx(tx, &receipt_key, true, "IDEMPOTENCY_EXPIRED")?;
                let receipt: PublicationReceipt = parse(&bytes)?;
                if receipt.request != publication
                    || receipt.result.name != resource
                    || receipt.principal != principal
                {
                    return Err(Error::new(
                        "OPERATION_CONFLICT",
                        "publication request ID already used",
                    ));
                }
                return Ok(receipt.result);
            }
            // Pre-retention releases used the client request ID as the version.
            if let Some(bytes) = tx.get(&prefix(b'V', publication.version))? {
                let old: PublishedLookup = parse(&bytes)?;
                if old.version.is_nil() {
                    retention::check_tx(
                        tx,
                        &prefix(b'V', publication.version),
                        true,
                        "IDEMPOTENCY_EXPIRED",
                    )?;
                    if old.name == resource && old.publication == publication {
                        return parse_published(&bytes);
                    }
                    return Err(Error::new(
                        "OPERATION_CONFLICT",
                        "legacy publication request ID already used",
                    ));
                }
            }
            retention::authorize_new(tx, publication.retry_token, principal, &self.history())?;
            let pointer = named(b"P", resource);
            let previous: Option<Uuid> =
                tx.get(&pointer)?.map(|bytes| parse(&bytes)).transpose()?;
            if previous != publication.expected_version {
                return Err(Error::new("REVISION_CONFLICT", "published version changed"));
            }
            let collection = collection_tx(tx, &publication.collection)?;
            let indexes = indexes_tx(tx, collection.id)?;
            if indexes.iter().any(|index| index.state != IndexState::Ready) {
                return Err(Error::new(
                    "INDEX_NOT_READY",
                    "finish all index builds before publication",
                ));
            }
            if !publication.lookup.is_empty() {
                let lookup: LookupDefinition = parse(
                    &tx.get(&named(&prefix(b'L', collection.id), &publication.lookup))?
                        .ok_or_else(|| Error::missing("lookup"))?,
                )?;
                if !indexes.iter().any(|index| index.spec.name == lookup.index) {
                    return Err(Error::missing("lookup index"));
                }
            }
            if let Some(previous) = previous {
                let target = prefix(b'V', previous);
                let old = parse_published(
                    &tx.get(&target)?
                        .ok_or_else(|| Error::corrupt("publication pointer"))?,
                )?;
                retention::schedule(
                    tx,
                    &target,
                    Expiration::Publication {
                        version: previous,
                        collection: old.collection_id,
                        name: old.publication.collection,
                    },
                )?;
            }
            let out = PublishedLookup {
                version: Uuid::new_v4(),
                name: resource.into(),
                publication: publication.clone(),
                collection_id: collection.id,
                commit_seq: tx.seq,
            };
            put(tx, prefix(b'S', collection.id), &true)?;
            put(tx, pointer, &out.version)?;
            put(tx, prefix(b'V', out.version), &out)?;
            put(
                tx,
                retention::key(
                    &retention::key(retention::REFERENCES, collection.id.as_bytes()),
                    out.version.as_bytes(),
                ),
                &true,
            )?;
            put(
                tx,
                receipt_key.clone(),
                &PublicationReceipt {
                    request: publication.clone(),
                    result: out.clone(),
                    principal: principal.into(),
                },
            )?;
            retention::schedule_receipt(tx, &receipt_key, publication.retry_token)?;
            tx.check_expanded_limits()?;
            Ok(out)
        })
    }

    pub fn published_lookup(
        &self,
        resource: &str,
        version: Option<Uuid>,
    ) -> Result<PublishedLookup> {
        name(resource)?;
        let snapshot = self.engine().snapshot()?;
        published(&snapshot, resource, version, true)
    }

    /// Resolves the pointer and executes the whole batch in one read view.
    /// Historical versions remain readable until the tenant retention deadline.
    pub fn lookup_published(
        &self,
        resource: &str,
        version: Option<Uuid>,
        inputs: &[Value],
    ) -> Result<PublishedResult> {
        self.read_with(&crate::ReadOptions::default())?
            .lookup_published(resource, version, inputs)
    }
    pub(crate) fn lookup_published_controlled(
        &self,
        resource: &str,
        version: Option<Uuid>,
        inputs: &[Value],
        budget: &crate::read::ReadBudget,
    ) -> Result<PublishedResult> {
        budget.check()?;
        name(resource)?;
        let snapshot = self.engine().snapshot()?;
        let pinned = published(&snapshot, resource, version, true)?;
        if pinned.publication.lookup.is_empty() {
            return Err(Error::invalid(
                "dataset has no default lookup; use published reads",
            ));
        }
        let result = self.lookup_snapshot(
            &pinned.publication.collection,
            &pinned.publication.lookup,
            inputs,
            snapshot,
            budget,
        )?;
        Ok(PublishedResult {
            version: pinned.version,
            result,
        })
    }
}

pub(super) fn published(
    snapshot: &crate::storage::Snapshot,
    resource: &str,
    version: Option<Uuid>,
    check_expiration: bool,
) -> Result<PublishedLookup> {
    let mut stats = ReadStats::default();
    let version = match version {
        Some(version) => version,
        None => parse(
            &snapshot
                .get(&named(b"P", resource), &mut stats)?
                .ok_or_else(|| Error::missing("published lookup"))?,
        )?,
    };
    let out: PublishedLookup = parse_published(
        &snapshot
            .get(&prefix(b'V', version), &mut stats)?
            .ok_or_else(|| {
                Error::new("VERSION_UNAVAILABLE", "published version absent or expired")
            })?,
    )?;
    let current: Option<Uuid> = snapshot
        .get(&named(b"P", resource), &mut stats)?
        .map(|b| parse(&b))
        .transpose()?;
    if check_expiration && current != Some(version) {
        retention::check_snapshot(
            snapshot,
            &prefix(b'V', version),
            true,
            "VERSION_UNAVAILABLE",
        )?;
    }
    if out.name != resource {
        return Err(Error::new(
            "VERSION_UNAVAILABLE",
            "published version absent or expired",
        ));
    }
    Ok(out)
}
